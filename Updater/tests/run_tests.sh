#!/bin/bash
# Интеграционные тесты обновлятора под mono: мок-GitHub + "игра" (Harness), в которой работает тот же код ShadowUpdateGate.
export LANG=C.UTF-8 LC_ALL=C.UTF-8
cd "$(dirname "$0")"; T=/tmp/stt; PORT=18765; UPD=$(cd .. && pwd)
rm -rf $T; mkdir -p $T/srv
mcs -out:$T/harness.exe -r:System.dll Harness.cs ../../XUnity.AutoTranslator.Plugin.Core/Updating/ShadowUpdateGate.cs 2>&1 | grep -v warning
R=${NETFX_REF:-/usr/lib/mono/4.8-api}
[ -f "$R/mscorlib.dll" ] || { echo "нет справочных сборок: $R (установите mono-devel)"; exit 1; }
mcs -noconfig -nostdlib -target:winexe -platform:anycpu -optimize+ -nowarn:1591 -out:$T/ShadowTranslate.Updater.exe \
  -r:$R/mscorlib.dll -r:$R/System.dll -r:$R/System.Core.dll -r:$R/System.IO.Compression.dll -r:$R/System.IO.Compression.FileSystem.dll \
  -r:$R/System.Web.Extensions.dll -r:$R/Facades/System.Runtime.dll $UPD/ShadowTranslate.Updater/*.cs || exit 1
if command -v monodis >/dev/null 2>&1 && monodis --memberref $T/ShadowTranslate.Updater.exe 2>/dev/null | grep -q 'instance string\[\](char, valuetype \[mscorlib\]System.StringSplitOptions)'; then
  echo "ОШИБКА: вызов String.Split(char, StringSplitOptions) отсутствует в .NET Framework"; exit 1
fi
PASS=0; FAILN=0
ok(){ echo "  PASS: $1"; PASS=$((PASS+1)); }
bad(){ echo "  FAIL: $1"; FAILN=$((FAILN+1)); }
chk(){ if eval "$2"; then ok "$1"; else bad "$1"; fi; }

python3 make_zip.py $T/srv/v020.zip 0.2.0 >/dev/null
python3 make_zip.py $T/srv/v030.zip 0.3.0 wrap >/dev/null
python3 make_zip.py $T/srv/slip.zip 0.4.0 slip >/dev/null
echo ok > $T/mode

start_srv(){ python3 mock_github.py $PORT $T/srv/$1 $T/mode ${2:-0.2.0} 2>$T/srv.log & SRV=$!; sleep 0.7; }
stop_srv(){ kill $SRV 2>/dev/null; wait $SRV 2>/dev/null; }

setup_game(){  # $1 = extra ini lines
  G=$T/game; rm -rf $G; mkdir -p $G/ShadowTranslate $G/BepInEx/plugins/XUnity.AutoTranslator $G/BepInEx/config $G/BepInEx/Translation/ru/Text
  cp $T/ShadowTranslate.Updater.exe $G/ShadowTranslate/
  printf 'PLUGIN v0.1.0' > $G/BepInEx/plugins/XUnity.AutoTranslator/XUnity.AutoTranslator.Plugin.Core.dll
  printf 'UserConfig=1\n' > $G/BepInEx/config/AutoTranslatorConfig.ini
  printf 'hello=старый\n' > $G/BepInEx/Translation/ru/Text/_AutoGeneratedTranslations.txt
  printf 'WINHTTP-SAME' > $G/winhttp.dll
  printf 'obsolete' > $G/BepInEx/plugins/Obsolete.dll
  printf 'BepInEx/plugins/Obsolete.dll\nwinhttp.dll\n' > $G/ShadowTranslate/installed.manifest
  printf '#!/bin/sh\necho "args=$* just=$SHADOWTRANSLATE_JUST_UPDATED" >> %s/relaunched.txt\n' $T > $G/fakegame.sh; chmod +x $G/fakegame.sh
  rm -f $T/relaunched.txt
  cat > $G/ShadowTranslate/updater.ini <<INI
[Updater]
Console=never
CheckTimeoutSeconds=5
StallSeconds=5
Retries=2
UseMirrors=false
$1
[Advanced]
WebBase=http://127.0.0.1:$PORT
ApiBase=http://127.0.0.1:$PORT
RawBase=http://127.0.0.1:$PORT/raw
INI
}
updater_alive(){ ps -eo stat,args | grep "ShadowTranslate.Updater.exe" | grep -v "^Z" | grep -v grep >/dev/null; }
run_game(){  # $1 = версия плагина; вывод в $T/out.txt
  FAKE_GAME_EXE=$G/fakegame.sh PLUGIN_VERSION=$1 timeout 120 mono $T/harness.exe --foo "bar baz" > $T/out.txt 2>&1
  for i in $(seq 1 100); do updater_alive || break; sleep 0.3; done; sleep 0.3
}
leftovers(){ [ ! -e $G/ShadowTranslate/stage ] && [ ! -e $G/ShadowTranslate/backup ] && [ ! -e $G/ShadowTranslate/apply.journal ]; }
updated(){ grep -q "PLUGIN v$1" $G/BepInEx/plugins/XUnity.AutoTranslator/XUnity.AutoTranslator.Plugin.Core.dll; }
untouched(){ grep -q 'PLUGIN v0.1.0' $G/BepInEx/plugins/XUnity.AutoTranslator/XUnity.AutoTranslator.Plugin.Core.dll && [ -f $G/BepInEx/plugins/Obsolete.dll ]; }

echo "== 1. Штатное обновление 0.1.0 -> 0.2.0"
setup_game; start_srv v020.zip; run_game 0.1.0
chk "игра закрыта обновлятором (нет GAME_CONTINUES)" "! grep -q GAME_CONTINUES $T/out.txt"
chk "игра перезапущена с исходными аргументами и защитой от цикла" "grep -q 'args=--foo bar baz just=1' $T/relaunched.txt"
chk "DLL заменена на новую" "updated 0.2.0"
chk "конфиг заменён версией из релиза (Preserve пуст по умолчанию)" "grep -q UpstreamDefault=1 $G/BepInEx/config/AutoTranslatorConfig.ini"
chk "перевод обновлён" "grep -q 'v0.2.0' $G/BepInEx/Translation/ru/Text/_AutoGeneratedTranslations.txt"
chk "устаревший файл удалён (по манифесту)" "[ ! -e $G/BepInEx/plugins/Obsolete.dll ]"
chk "новый файл добавлен" "[ -f $G/BepInEx/plugins/NewInThisVersion.txt ]"
chk "папка ShadowTranslate/ из архива НЕ применена" "! grep -q MALICIOUS $G/ShadowTranslate/ShadowTranslate.Updater.exe"
chk "state.ini: tag=0.2.0" "grep -q 'tag=0.2.0' $G/ShadowTranslate/state.ini"
chk "нет остатков stage/backup/journal" leftovers
chk "старый перевод сохранён в backup-translations" "grep -rq старый $G/ShadowTranslate/backup-translations"
chk "манифест записан" "grep -q NewInThisVersion $G/ShadowTranslate/installed.manifest"
echo "== 2. Повторный запуск: версия актуальна"
rm -f $T/relaunched.txt; run_game 0.2.0
chk "игра продолжает без перезапуска" "grep -q GAME_CONTINUES $T/out.txt && [ ! -f $T/relaunched.txt ]"
echo "== 2b. Перезапущенная игра (JUST_UPDATED=1) не проверяет повторно"
SHADOWTRANSLATE_JUST_UPDATED=1 FAKE_GAME_EXE=$G/fakegame.sh PLUGIN_VERSION=0.1.0 mono $T/harness.exe > $T/out.txt 2>&1
chk "проверка пропущена" "grep -q 'проверка пропущена' $T/out.txt && grep -q GAME_CONTINUES $T/out.txt"
stop_srv
echo "== 2c. Preserve=BepInEx/config/* сохраняет конфиг пользователя"
setup_game "Preserve=BepInEx/config/*"; start_srv v020.zip; run_game 0.1.0
chk "DLL заменена" "updated 0.2.0"
chk "конфиг пользователя сохранён" "grep -q UserConfig=1 $G/BepInEx/config/AutoTranslatorConfig.ini"
stop_srv

echo "== 3. Нет связи (сервер выключен)"
setup_game; run_game 0.1.0
chk "игра продолжает запуск" "grep -q GAME_CONTINUES $T/out.txt"
chk "файлы не тронуты" untouched
chk "время ожидания в пределах таймаута" "[ \$(grep -o 'GAME_CONTINUES after [0-9]*' $T/out.txt | grep -o '[0-9]*\$') -lt 9000 ]"

echo "== 4. github.com недоступен (503) -> запасной канал API"
setup_game; echo no-web > $T/mode; start_srv v020.zip; run_game 0.1.0
chk "обновление прошло через API" "grep -q 'api.github.com' $G/ShadowTranslate/updater.log && updated 0.2.0"
stop_srv

echo "== 5. Всё заблокировано (HTTP 451)"
setup_game; echo blocked > $T/mode; start_srv v020.zip; run_game 0.1.0
chk "игра продолжает, файлы не тронуты" "grep -q GAME_CONTINUES $T/out.txt && untouched"
chk "причина понятно записана в лог" "grep -q '451' $G/ShadowTranslate/updater.log"
stop_srv

echo "== 6. Обрыв соединения на 40% -> докачка"
setup_game; echo drop > $T/mode; start_srv v020.zip; run_game 0.1.0
chk "обновление успешно" "updated 0.2.0 && grep -q 'докачка' $G/ShadowTranslate/updater.log"
stop_srv

echo "== 7. Подмена/порча файла (sha256 не совпадает)"
setup_game; echo badhash > $T/mode; start_srv v020.zip; run_game 0.1.0
chk "игра продолжает, файлы не тронуты" "grep -q GAME_CONTINUES $T/out.txt && untouched"
chk "в логе: SHA-256 не совпал" "grep -q 'SHA-256 не совпал' $G/ShadowTranslate/updater.log"
echo "   повторный запуск сразу после неудачи -> пауза (backoff)"
run_game 0.1.0
chk "обновление пропущено из-за паузы" "grep -q 'пауза ещё' $G/ShadowTranslate/updater.log && grep -q GAME_CONTINUES $T/out.txt"
stop_srv

echo "== 8. Соединение зависло (stall)"
setup_game; echo stall > $T/mode; start_srv v020.zip; run_game 0.1.0
chk "игра продолжает, файлы не тронуты" "grep -q GAME_CONTINUES $T/out.txt && untouched"
stop_srv

echo "== 9. Скачивание 404"
setup_game; echo 404 > $T/mode; start_srv v020.zip; run_game 0.1.0
chk "игра продолжает, файлы не тронуты" "grep -q GAME_CONTINUES $T/out.txt && untouched"
stop_srv

echo "== 10. Прямая ссылка мертва, зеркало работает (с проверкой sha256)"
setup_game "UseMirrors=true
Mirrors=http://127.0.0.1:$PORT/m/{url}"; echo direct-dead > $T/mode; start_srv v020.zip; run_game 0.1.0
chk "обновление через зеркало" "updated 0.2.0"
stop_srv
echo "== 10b. Зеркало отдаёт подделку при известном sha256"
setup_game "UseMirrors=true
Mirrors=http://127.0.0.1:$PORT/m/{url}"; echo mirror-bad > $T/mode; start_srv v020.zip; run_game 0.1.0
chk "подделка отвергнута, файлы не тронуты" "grep -q GAME_CONTINUES $T/out.txt && untouched && grep -q 'SHA-256 не совпал' $G/ShadowTranslate/updater.log"
stop_srv

echo "== 11. Отсечение корневой папки архива (ShadowTranslate-0.3.0/...)"
setup_game; echo ok > $T/mode; start_srv v030.zip 0.3.0; run_game 0.1.0
chk "обновление до 0.3.0 прошло" "updated 0.3.0 && grep -q 'отброшена' $G/ShadowTranslate/updater.log"
stop_srv

echo "== 12. Архив с путём ../evil.txt (zip-slip)"
setup_game; echo ok > $T/mode; start_srv slip.zip 0.4.0; run_game 0.1.0
chk "отклонён, файлы не тронуты, evil.txt не создан" "grep -q GAME_CONTINUES $T/out.txt && untouched && [ ! -e $T/game/../evil.txt ] && [ ! -e $T/evil.txt ]"
stop_srv

echo "== 13. Сбой посреди замены -> автоматический откат"
setup_game; mkdir -p $G/BepInEx/plugins/NewInThisVersion.txt   # на месте нового файла - папка, File.Move упадёт
echo ok > $T/mode; start_srv v020.zip; run_game 0.1.0
chk "прежняя версия восстановлена (DLL, Obsolete)" untouched
chk "в логе есть откат" "grep -q 'Прежняя версия восстановлена\|прежняя версия восстановлена' $G/ShadowTranslate/updater.log"
chk "игра перезапущена (старой версией)" "[ -f $T/relaunched.txt ]"
chk "нет остатков" leftovers
stop_srv

echo "== 14. Восстановление после аварии (журнал без COMMIT)"
setup_game; mkdir -p $G/ShadowTranslate/backup/BepInEx/plugins/XUnity.AutoTranslator
printf 'PLUGIN v0.1.0' > $G/ShadowTranslate/backup/BepInEx/plugins/XUnity.AutoTranslator/XUnity.AutoTranslator.Plugin.Core.dll
printf 'PLUGIN HALF-WRITTEN' > $G/BepInEx/plugins/XUnity.AutoTranslator/XUnity.AutoTranslator.Plugin.Core.dll
printf 'BEGIN 0.2.0\nREP BepInEx/plugins/XUnity.AutoTranslator/XUnity.AutoTranslator.Plugin.Core.dll\n' > $G/ShadowTranslate/apply.journal
run_game 0.1.0
chk "файл возвращён из backup" "grep -q 'PLUGIN v0.1.0' $G/BepInEx/plugins/XUnity.AutoTranslator/XUnity.AutoTranslator.Plugin.Core.dll"
chk "игра перезапущена после отката" "[ -f $T/relaunched.txt ]"
chk "журнал удалён" "[ ! -e $G/ShadowTranslate/apply.journal ]"

echo; echo "ИТОГО: PASS=$PASS FAIL=$FAILN"; [ $FAILN -eq 0 ]
